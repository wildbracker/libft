#include "libft.h"

char	*ft_strmapi(char const *s, char (*f)(unsigned int, char))
{
	size_t	i;
	char	*str;

	str = ft_strdup(s);
	i = 0;
	while (str && i < ft_strlen(str))
	{
		str[i] = f(i, str[i]);
		i++;
	}
	return (str);
}
